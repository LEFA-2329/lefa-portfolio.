import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Edit the .html files, then run npm run build. No runtime HTML evaluator is used.
export function compileHtmlPages() {
  const pages = {};
  for (const [prefix, folder] of [
    ['studylab', '../dist/learn/pages/'],
    ['portfolio', '../dist/portfolio/project-stories/'],
  ]) {
    const directory = new URL(folder, import.meta.url);
    for (const name of readdirSync(directory)
      .filter((n) => n.endsWith('.html'))
      .sort()) {
      const html = readFileSync(new URL(name, directory), 'utf8');
      if (
        /<\s*(script|iframe|object|embed|base)\b/i.test(html) ||
        /\son[a-z]+\s*=/i.test(html) ||
        /(?:href|src)\s*=\s*["']\s*(?:javascript|vbscript):/i.test(html)
      ) {
        throw new Error('Executable content is not permitted in page templates: ' + name);
      }
      pages[prefix + '/' + name.slice(0, -5)] = html;
    }
  }
  return (
    '// Generated by npm run build. Edit the matching .html source files.\nexport const htmlPages = ' +
    JSON.stringify(pages, null, 2) +
    ';\n'
  );
}
export const output = new URL('../dist/shared/compiled-html-pages.mjs', import.meta.url);
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const expected = compileHtmlPages();
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== expected)
      throw new Error(
        'HTML pages changed. Run npm run build and commit the generated file.',
      );
  } else {
    writeFileSync(output, expected);
    console.log('Built editable HTML page templates.');
  }
}
